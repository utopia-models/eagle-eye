#!/usr/bin/env python3
"""claire_takes.py: build Claire's own-network VSL take list from HER contacts (knowledge#14327, spec
`net/work/specs/13429-claire-youk-client/vsl/network-vsl.md`).

Claire records; the fleet does the rest. Source = the claire@utopiamodels.ai contacts (People API, domain-wide
delegation), never Tyler's roster and never a question to her. One row per person who has a phone or email.
The proof line comes from the contact's LABEL (Google contact group): FCPS, Chantilly, Encore, UCSB, Family friends.
A contact with no matching label gets NO proof line (nothing is guessed).

    claire_takes.py plan   [--contacts F.json]   # print the take list (name, group, number, email)
    claire_takes.py build  [--contacts F.json]   # write specs/13429-.../vsl/takes.tsv and takes.md (Vizier script)
    claire_takes.py --self-test
Exit 0 = rows built, 3 = no contacts yet (the honest empty state; session-1 step 5 imports them).
"""
from __future__ import annotations

import json
import subprocess
import sys
import urllib.request
from pathlib import Path

KB = Path(__file__).resolve().parents[4]
VSL = KB / "net/work/specs/13429-claire-youk-client/vsl"
SCOPE = "https://www.googleapis.com/auth/contacts.readonly"
SUBJECT = "claire@utopiamodels.ai"
PROOF = {  # network-vsl.md "Proof lines"
    "fcps": "I was one of three students representing Chantilly on the county's Student Advisory Council.",
    "chantilly": "I was on the SGA executive board, running events for the whole school.",
    "encore": "I've taught at Encore since I was little, and I ran its social media for two years.",
    "ucsb": "I'm in the founding class of Kappa Alpha Pi, the pre-law fraternity, at UCSB.",
    "family friends": "I'm already doing contract and compliance research part-time for a small company.",
}
BODY = """Hi {first}, it's Claire.
I'm at UC Santa Barbara now, studying political science, and I'm on the pre-law track.
I'll be home in Fairfax from July to September next summer.
I'm looking for a paid internship then, in a law office, a government office, or a policy group, around Northern Virginia or DC.
{proof}If you know anyone who works somewhere like that, could you introduce me, or tell me who to reach out to?
Thank you so much. You can just reply to this text.
"""


def fetch() -> list[dict]:
    tok = subprocess.run(["cred", "google-token", SCOPE, SUBJECT], capture_output=True, text=True, timeout=90).stdout.strip()
    if len(tok) < 50:
        raise RuntimeError("contacts token mint failed")
    h = {"Authorization": "Bearer " + tok}
    base = "https://people.googleapis.com/v1/"
    def get(u):
        with urllib.request.urlopen(urllib.request.Request(base + u, headers=h), timeout=60) as r:
            return json.load(r)
    groups = {g["resourceName"]: g.get("name", "") for g in get("contactGroups?pageSize=200").get("contactGroups", [])}
    out, page = [], ""
    while True:
        d = get("people/me/connections?pageSize=500&personFields=names,phoneNumbers,emailAddresses,memberships"
                + (f"&pageToken={page}" if page else ""))
        for p in d.get("connections", []):
            p["_groups"] = [groups.get(m.get("contactGroupMembership", {}).get("contactGroupResourceName", ""), "")
                            for m in p.get("memberships", [])]
            out.append(p)
        page = d.get("nextPageToken", "")
        if not page:
            return out


def rows(people: list[dict]) -> list[dict]:
    res = []
    for p in people:
        name = (p.get("names") or [{}])[0].get("displayName", "").strip()
        phone = (p.get("phoneNumbers") or [{}])[0].get("canonicalForm") or (p.get("phoneNumbers") or [{}])[0].get("value", "")
        email = (p.get("emailAddresses") or [{}])[0].get("value", "")
        if not name or not (phone or email):
            continue
        group = next((g for g in p.get("_groups", []) if g.lower() in PROOF), "")
        res.append({"name": name, "group": group, "proof": PROOF.get(group.lower(), ""), "number": phone, "email": email})
    return sorted(res, key=lambda r: r["name"].lower())


def script(rs: list[dict]) -> str:
    out = ["# Claire's network takes (generated by claire_takes.py; one `##` per person)\n"]
    for r in rs:
        proof = r["proof"] + "\n" if r["proof"] else ""
        out.append(f"## Take: {r['name'].split()[0]}\n" + BODY.format(first=r["name"].split()[0], proof=proof))
    return "\n".join(out)


def main(argv: list[str]) -> int:
    if "--self-test" in argv:
        t = rows([{"names": [{"displayName": "Ann Lee"}], "phoneNumbers": [{"canonicalForm": "+15550001111"}], "_groups": ["Encore"]},
                  {"names": [{"displayName": "Bo Ray"}], "emailAddresses": [{"value": "b@x.org"}], "_groups": []},
                  {"names": [{"displayName": "No Channel"}]}])
        assert [r["name"] for r in t] == ["Ann Lee", "Bo Ray"] and t[0]["proof"].startswith("I've taught") and t[1]["proof"] == ""
        s = script(t)
        assert "Hi Ann, it's Claire." in s and "Hi Bo, it's Claire." in s and "\n\n" not in s.split("## Take: Bo")[1].strip()
        print("claire_takes self-test: ok")
        return 0
    cmd = argv[0] if argv else "plan"
    people = json.load(open(argv[argv.index("--contacts") + 1])) if "--contacts" in argv else fetch()
    rs = rows(people)
    if not rs:
        print(json.dumps({"takes": 0, "note": "claire@ has no usable contacts yet (session-1.md step 5 imports them)"}))
        return 3
    if cmd == "build":
        (VSL / "takes.tsv").write_text("name\tgroup\tproof\tnumber\temail\n" + "".join(
            "\t".join(r[k] for k in ("name", "group", "proof", "number", "email")) + "\n" for r in rs))
        (VSL / "takes.md").write_text(script(rs))
    print(json.dumps({"takes": len(rs), "labeled": sum(1 for r in rs if r["group"])}))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
