#!/usr/bin/env python3
"""vsl_labels.py: corpus labels derived by script, never by a person (Part of #15166).

  vsl_labels.py sync [--db proposals.db] [--check]   rewrite the generated block of reference/manifest.yaml; --check exits 1 if it is stale
  vsl_labels.py show                                  the merged label of every labelled file

Status per file, strongest evidence first:
  curated   an `entries:` row in manifest.yaml (Tyler's recorded accept/reject) always wins
  won       proposals.db row with hired_at whose letter_file is the file
  accepted  proposals.db row with replied/interview/call_at (the client answered the letter)
  rejected  proposals.db row with declined_at and nothing better; or a golden/script file the mechanical copy gate fails on a
            banned phrase (the same list Tyler wrote); the file stays in the corpus as an anti-example
  unknown   everything else (never guessed)
The generated block sits under MARK; everything above it is hand-kept and never touched. proposals.db absent -> the gate-derived rows only.
"""
import os
import re
import sqlite3
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORK = HERE.parents[1]
sys.path.insert(0, str(HERE))
import script_check  # noqa: E402
import vsl_copy  # noqa: E402

MANIFEST = HERE / "reference/manifest.yaml"
MARK = "# ---- generated by vsl_labels.py sync: do not edit below this line ----"
DB = os.environ.get("UPWORK_PROPOSALS_DB", str(Path.home() / ".claude/state/net/upwork/proposals.db"))
RANK = {"won": 4, "accepted": 3, "unknown": 0, "rejected": -1}


def curated():
    import yaml
    head = MANIFEST.read_text().split(MARK)[0]
    return (yaml.safe_load(head) or {}).get("entries", {})


def from_db(db):
    """-> {relpath: (status, why)} from proposals.db outcomes."""
    out = {}
    if not Path(db).exists():
        return out
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    rows = con.execute("select letter_file, hired_at, replied_at, interview_at, call_at, declined_at from proposals "
                       "where letter_file is not null and letter_file != ''").fetchall()
    for lf, hired, rep, iv, call, dec in rows:
        p = Path(lf)
        try:
            rel = str(p.resolve().relative_to(WORK)) if p.is_absolute() else str(p).split("net/work/")[-1]
        except ValueError:
            rel = str(p).split("net/work/")[-1]
        if hired:
            st, why = "won", "proposals.db hired_at"
        elif rep or iv or call:
            st, why = "accepted", "proposals.db client replied"
        elif dec:
            st, why = "rejected", "proposals.db declined_at"
        else:
            continue
        if RANK[st] > RANK.get(out.get(rel, ("unknown",))[0], 0) or rel not in out:
            out[rel] = (st, why)
    return out


def from_gate():
    """Golden/script takes that fail the banned-phrase list are rejected by the same rule Tyler wrote."""
    out = {}
    for pat in ("_tools/vsl/tests/golden/*.md", "vsl/**/tyler-script.md", "vsl/**/horus-script.md"):
        for f in sorted(WORK.glob(pat)):
            body = f.read_text(errors="replace")
            hits = [r for r in vsl_copy.check_copy(body, vale=False)[0] if "banned" in r]
            if hits:
                out[str(f.relative_to(WORK))] = ("rejected", "copy gate: " + hits[0][:80].replace('"', "'"))
    return out


def derive(db=DB):
    """Gate-derived labels first, then proposals.db over them (a real outcome outranks a phrase list); curated rows are excluded."""
    cur = curated()
    merged = dict(from_gate())
    merged.update(from_db(db))
    return {r: v for r, v in merged.items() if r not in cur}


def render(db=DB):
    d = derive(db)
    lines = [MARK, "auto:"] + [f'  {r}: {{status: {s}, note: "{w}"}}' for r, (s, w) in sorted(d.items())]
    return "\n".join(lines) + "\n"


def sync(db=DB, check=False):
    head = MANIFEST.read_text().split(MARK)[0].rstrip("\n") + "\n"
    new = head + render(db)
    if check:
        return MANIFEST.read_text() == new
    MANIFEST.write_text(new)
    return True


def merged_status():
    import yaml
    doc = yaml.safe_load(MANIFEST.read_text()) or {}
    out = {r: dict(v) for r, v in (doc.get("auto") or {}).items()}
    out.update({r: dict(v) for r, v in (doc.get("entries") or {}).items()})
    return out


def main(argv):
    if not argv or argv[0] not in ("sync", "show"):
        print(__doc__)
        return 2
    db = argv[argv.index("--db") + 1] if "--db" in argv else DB
    if argv[0] == "sync":
        ok = sync(db, "--check" in argv)
        print(("fresh" if ok else "STALE") if "--check" in argv else f"synced {len(derive(db))} auto labels (db {'present' if Path(db).exists() else 'absent'})")
        return 0 if ok else 1
    for r, v in sorted(merged_status().items()):
        print(f"{v.get('status', 'unknown'):9} {r}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
